#!/usr/bin/env python3
"""Build docs/shorts-reels.md (all Shorts + Reels, with follow/subscribe CTAs) from the Bible.
Run: python scripts/shorts_to_md.py   (no AI tokens needed; re-run after any Bible edit)"""
import glob, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
files = sorted(f for f in glob.glob(str(root / "docs/**/*.md"), recursive=True)
               if re.search(r"(^|/)(m\d+|M\d+ )", f))
CTA_VOICE = {  # spoken line added at the very end of the Short, rotated so it never feels copy-pasted
    "S1": "Follow for the next one.",
    "S2": "Subscribe, and learn C one episode at a time.",
    "S3": "Follow Koding Konkani, so you never ship this bug.",
    "S4": "Follow for more bad jokes. Keep coding, says Xecxec!",
    "S5": "Comment your answer, then follow for the solution.",
}
out = ["# Koding Konkani - Shorts and Reels pack (430)\n",
"> Generated by `scripts/shorts_to_md.py` from the Episode Bible. Do not hand-edit; edit the Bible and re-run.\n",
"## Fill in once\n",
"| Setting | Value |\n|---|---|\n| Instagram handle | `@YOUR_IG_HANDLE` (replace everywhere) |\n| YouTube channel | `Koding Konkani` |\n| Link in bio | `YOUR_LINK` |\n",
"## How each Short ends (all 430)\n",
"- **Last 2 seconds, on screen:** `FOLLOW @YOUR_IG_HANDLE` (Instagram) or `SUBSCRIBE: Koding Konkani` (YouTube Shorts), plus the badge `Full video: EP NN`.",
"- **Spoken CTA** (one short line, rotated by Short type, shown under each script below).",
"- **Pinned comment:** `Full episode on the channel, link in bio. Follow and subscribe so you don't miss EP NN+1!`",
"- Post the same video to Instagram Reels and YouTube Shorts; use the matching caption line below.\n"]
n = 0
for f in files:
    txt = pathlib.Path(f).read_text(encoding="utf-8")
    for m in re.finditer(r"^### Shorts for EP (\d+)\s*\n(.*?)(?=^## EP |\Z)", txt, re.S | re.M):
        ep, body = m.group(1), m.group(2)
        title = re.search(r"^## EP %s . (.*)$" % ep, txt, re.M)
        out.append(f"\n---\n\n## EP {ep} - {title.group(1).strip() if title else ''}\n")
        for s in re.finditer(r"^\*\*(S\d) . (.*?)\*\* . (.*?)\n(.*?)(?=^\*\*S\d |\Z)", body, re.S | re.M):
            sid, name, meta, rest = s.groups()
            def field(k):
                r = re.search(r"- \*\*%s[^*]*\*\*\s*(.*)" % k, rest)
                return r.group(1).strip() if r else ""
            cap = field("Caption")
            tags = " ".join(re.findall(r"#\w+", cap)); text = re.sub(r"\s*#\w+", "", cap).strip()
            n += 1
            out.append(f"### EP {ep} {sid} - {name}\n- **Length / source:** {meta.strip()}\n- **Hook (0-1.5s):** {field('Hook')}\n"
                       f"- **Script:** {field('Script')} **{CTA_VOICE[sid]}**\n- **On-screen text:** {field('On-screen')}\n"
                       f"- **End card (last 2s):** FOLLOW @YOUR_IG_HANDLE / SUBSCRIBE: Koding Konkani - Full video: EP {ep}\n"
                       f"- **Instagram caption:** {text} Follow @YOUR_IG_HANDLE for a new C lesson daily. Full episode: link in bio. {tags}\n"
                       f"- **YouTube Shorts title/caption:** {name} | C Programming EP {ep} - {text} Subscribe to Koding Konkani for the full episode. {tags} #shorts\n")
pathlib.Path(root / "docs/shorts-reels.md").write_text("\n".join(out), encoding="utf-8")
print("shorts written:", n)
sys.exit(0 if n == 430 else 1)
